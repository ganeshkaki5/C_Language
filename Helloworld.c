#include<stdio.h>
int main()
{
 int num=15,c=0;

 for(int i=31; i>=0;i--)
 {
    if((num>>i)&1)
       c++;
    
   printf("%d", (num>>i)&1);
 }
  printf("\n");
  printf("set = %d, clear =%d \n", c, 32-c);
  
    return 0;
}
